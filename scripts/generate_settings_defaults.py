SETTINGS_HEADER = """\
// Generated by scripts/contracts.py. Do not edit by hand.
// Default values are generated from overture.db.models.settings.AppSettingsBase,
// overture.domain, overture.schemas.server_audit and overture.utils.http_security.
"""


def _max_length(schema: dict[str, Any], defs: dict[str, Any]) -> int:
    """The longest a JSON schema lets a string be, through ``$ref`` and ``anyOf``."""
    if "$ref" in schema:
        return _max_length(defs[schema["$ref"].rsplit("/", 1)[-1]], defs)
    if "maxLength" in schema:
        return schema["maxLength"]
    (limit,) = {
        _max_length(option, defs)
        for option in schema.get("anyOf", [])
        if option.get("type") != "null"
    }
    return limit


def _type_limit(annotation: Any) -> int:
    schema = TypeAdapter(annotation).json_schema()
    return _max_length(schema, schema.get("$defs", {}))


def _field_limit(model: type[BaseModel], field: str) -> int:
    schema = model.model_json_schema()
    return _max_length(schema["properties"][field], schema.get("$defs", {}))


def render_settings_defaults() -> str:
    """Render the AppSettingsBase defaults as a typed TypeScript contract."""
    defaults = AppSettingsBase.defaults()
    lines = [
        SETTINGS_HEADER.rstrip(),
        "",
        'import type { AppSettingsUpdate } from "./rest/types.gen";',
        "",
        "export const DEFAULT_APP_SETTINGS = {",
    ]
    lines.extend(f"  {key}: {json.dumps(defaults[key])}," for key in sorted(defaults))
    # Checked against the settings contract rather than frozen, so a list
    # default is the list type the settings hold.
    lines.append("} satisfies Required<AppSettingsUpdate>;")
    lines.append("")
    lines.append("export type AppSettingsDefaults = typeof DEFAULT_APP_SETTINGS;")
    lines.append("")
    lines.append(
        "// Shared constants, from overture.domain and overture.utils.http_security."
    )
    for name, value in (
        (
            "SERVER_DISPLAY_NAMES",
            {server.value: server.display_name for server in ServerType},
        ),
        (
            "SELECTED_ART_SOURCE_LABELS",
            {
                source.value: source.label
                for source in ArtSource
                if source is not ArtSource.OVERTUREDB
            },
        ),
        ("ART_SOURCE_LABELS", {source.value: source.label for source in ArtBulkSource}),
        (
            "THEME_SOURCE_LABELS",
            {source.value: source.label for source in ThemeBulkSource},
        ),
        (
            "CATALOG_SOURCES",
            sorted(
                {source.value for source in ArtBulkSource if source.catalog}
                | {source.value for source in ThemeBulkSource if source.catalog}
            ),
        ),
        (
            "METADATA_ISSUES",
            {
                issue.value: {
                    "label": issue.label,
                    "collections": issue.collections,
                    "showOnly": issue.show_only,
                    "needsCatalog": issue.needs_catalog,
                }
                for issue in MetadataIssue
            },
        ),
        (
            "LIBRARY_STATUS_FIELDS",
            [field.value for field, spec in FIELDS.items() if spec.library_only],
        ),
        ("FIELD_LABELS", {field.value: spec.label for field, spec in FIELDS.items()}),
        (
            "OPERATOR_LABELS",
            {operator.value: operator.label for operator in FilterOperator},
        ),
        (
            "SOURCE_OPERATOR_LABELS",
            {
                operator.value: label
                for operator in FilterOperator
                if (label := operator.membership_label) is not None
            },
        ),
        ("ORDER_LABELS", {order.value: order.label for order in CollectionOrder}),
        ("ASSET_LABELS", {asset.value: asset.label for asset in ServerAsset}),
        (
            "COLLECTION_POSTER_LABELS",
            {style.value: style.label for style in CollectionPosterStyle},
        ),
        ("AUDIT_STATUS_LABELS", {status.value: status.label for status in AuditStatus}),
        (
            "THEME_ID_SOURCE_LABELS",
            {source.value: source.label for source in ThemeIdSource},
        ),
        (
            "DIMENSION_LABELS",
            {dimension.value: spec.label for dimension, spec in DIMENSIONS.items()},
        ),
        (
            "TEXT_LIMITS",
            {
                "collectionTitle": _field_limit(CollectionCreate, "title"),
                "groupName": _type_limit(GroupName),
                "displayName": _type_limit(DisplayName),
                "apiKeyName": _field_limit(ApiKeyCreate, "name"),
                "setTitleFormat": _type_limit(SetTitleFormat),
                "setAffix": _field_limit(CollectionGeneratorBase, "strip_prefix"),
                "setValueName": _field_limit(CustomSetValue, "name"),
                "setAliasName": _field_limit(SetValueAlias, "name"),
                "sortTitleFormat": _type_limit(SortTitleFormat),
                "summaryFormat": _type_limit(SummaryFormat),
                "memberTagFormat": _type_limit(MemberTagFormat),
                "seasonalDate": _type_limit(SeasonalDate),
                "tmdbRegion": _field_limit(AppSettingsBase, "tmdb_region"),
            },
        ),
        ("ITEM_ART_TYPES", list(ITEM_ART_TYPES)),
        ("UNMANAGED_GROUP", UNMANAGED_GROUP),
        ("UNGROUPED_GROUP", UNGROUPED_GROUP),
        ("POLICY_SETTINGS", dict(POLICY_SETTINGS)),
        ("ASPECT_RATIOS", dict(ASPECT_RATIOS)),
        (
            "ASPECT_TOLERANCES",
            {
                tolerance.value: tolerance.fraction
                for tolerance in AspectRatioTolerance
                if tolerance.fraction is not None
            },
        ),
        ("SERVER_ASSETS", [asset.value for asset in ServerAsset]),
        (
            "SEASON_ART_TYPES",
            [art_type.value for art_type in ArtType if art_type.owned_by_season],
        ),
        ("DEFAULT_ART_SOURCE_ORDER", list(DEFAULT_ART_SOURCE_ORDER)),
        ("DEFAULT_THEME_SOURCE_ORDER", list(DEFAULT_THEME_SOURCE_ORDER)),
        ("MATCH_THRESHOLD_DEFAULT", MATCH_THRESHOLD_DEFAULT),
        ("ASSETS_MATCH_THRESHOLD_DEFAULT", ASSETS_MATCH_THRESHOLD_DEFAULT),
        ("MATCH_THRESHOLD_MAX", MATCH_THRESHOLD_MAX),
        ("PERFECT_MATCH_ONLY", PERFECT_MATCH_ONLY),
        ("YOUTUBE_ID_PATTERN", YOUTUBE_ID_PATTERN.pattern),
        ("CSRF_COOKIE", CSRF_COOKIE),
        ("CSRF_HEADER", CSRF_HEADER),
        ("MUTATING_METHODS", sorted(MUTATING_METHODS)),
        ("LOGIN_PATH", LOGIN_PATH),
        ("SIGNED_OUT_PATH", SIGNED_OUT_PATH),
    ):
        suffix = " as const" if isinstance(value, list | dict) else ""
        lines.append(f"export const {name} = {json.dumps(value)}{suffix};")
    lines.append("")
    return "\n".join(lines)
